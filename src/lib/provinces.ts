// مرتب‌سازی الفبایی فارسی (با حروف الفبای فارسی)
function faCompare(a: string, b: string): number {
  const order = "آابپتثجچحخدذرزژسشصضطظعغفقکگلمنوهی";
  const index = (ch: string) => {
    const i = order.indexOf(ch);
    return i === -1 ? order.length : i;
  };
  const len = Math.min(a.length, b.length);
  for (let i = 0; i < len; i++) {
    const d = index(a[i]) - index(b[i]);
    if (d !== 0) return d;
  }
  return a.length - b.length;
}

